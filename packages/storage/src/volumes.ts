import { statfs, readdir, lstat } from 'node:fs/promises';
import { join, resolve } from 'node:path';

/**
 * Docker named volumes used by ForgeOffice. The application containers see
 * each volume as a plain POSIX directory; nothing here knows about Docker.
 */
export type VolumeKey = 'mail' | 'drive' | 'team' | 'certs' | 'backups';

export interface ForgeVolume {
  key: VolumeKey;
  /** Docker named volume backing this mount (informational). */
  volume: string;
  description: string;
  /** Absolute path inside the container. */
  path: string;
}

const DEFINITIONS: Record<VolumeKey, { volume: string; dir: string; env: string; description: string }> = {
  mail: { volume: 'forge_mail_data', dir: 'mail', env: 'FORGE_MAIL_DIR', description: 'Raw MIME messages, Maildir stores & mail attachments' },
  drive: { volume: 'forge_drive_data', dir: 'drive', env: 'FORGE_DRIVE_DIR', description: 'ForgeDrive files, revisions, thumbnails & previews' },
  team: { volume: 'forge_team_media', dir: 'team', env: 'FORGE_TEAM_DIR', description: 'Chat file drops, voice notes & meeting recordings' },
  certs: { volume: 'forge_certs', dir: 'certs', env: 'FORGE_CERTS_DIR', description: 'TLS certificates, DKIM keys & OIDC signing keys' },
  backups: { volume: 'forge_backups', dir: 'backups', env: 'FORGE_BACKUPS_DIR', description: 'Automated snapshots generated by backups / forge-cli' },
};

/**
 * Resolve volume mount paths. Each path defaults to `<FORGE_DATA_ROOT>/<dir>`
 * (FORGE_DATA_ROOT defaults to `/data`) and can be overridden individually.
 */
export function resolveVolumes(env: NodeJS.ProcessEnv = process.env): Record<VolumeKey, ForgeVolume> {
  const root = resolve(env.FORGE_DATA_ROOT ?? '/data');
  const out = {} as Record<VolumeKey, ForgeVolume>;
  for (const [key, def] of Object.entries(DEFINITIONS) as [VolumeKey, (typeof DEFINITIONS)[VolumeKey]][]) {
    out[key] = { key, volume: def.volume, description: def.description, path: resolve(env[def.env] ?? join(root, def.dir)) };
  }
  return out;
}

export interface DiskUsage {
  totalBytes: number;
  freeBytes: number;
  availableBytes: number;
  usedBytes: number;
}

/** Filesystem-level usage of the filesystem that hosts `path` (statfs(2)). */
export async function diskUsage(path: string): Promise<DiskUsage> {
  const s = await statfs(path);
  const totalBytes = s.blocks * s.bsize;
  const freeBytes = s.bfree * s.bsize;
  return { totalBytes, freeBytes, availableBytes: s.bavail * s.bsize, usedBytes: totalBytes - freeBytes };
}

/**
 * Recursively sum the apparent size of all regular files under `path`.
 * Symlinks are not followed. Intended for background jobs, not request paths.
 */
export async function directorySize(path: string): Promise<{ bytes: number; files: number }> {
  let bytes = 0;
  let files = 0;
  const stack = [path];
  while (stack.length) {
    const dir = stack.pop()!;
    let entries;
    try {
      entries = await readdir(dir, { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) stack.push(full);
      else if (entry.isFile()) {
        try {
          bytes += (await lstat(full)).size;
          files++;
        } catch {
          /* file vanished during scan */
        }
      }
    }
  }
  return { bytes, files };
}
